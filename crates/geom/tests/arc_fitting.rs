#[test]
fn fit_contour_arcs_compresses_186_vertex_concentric_hole_into_2_arcs_and_6_lines_with_zero_endpoint_gap() {
    let hole = concentric_c0_hole();
    assert_eq!(hole.len(), 186);
    let pinned = vec![false; hole.len()];
    let segs = fit_contour_arcs(&hole, &pinned, 200e-9);

    let n_arcs = segs.iter().filter(|s| matches!(s.geom, DGeom::Arc { .. })).count();
    let n_lines = segs.iter().filter(|s| matches!(s.geom, DGeom::Line { .. })).count();
    assert_eq!(segs.len(), 8, "expected 2 arcs + 6 lines = 8 segments, got: {segs:?}");
    assert_eq!(n_arcs, 2, "expected 2 circular arcs");
    assert_eq!(n_lines, 6, "expected 6 straight slot lines");

    for s in &segs {
        if let DGeom::Arc { c, r, a0, sweep } = s.geom {
            assert!(norm2(c) < 25e-9, "fitted circle center {c:?} should be within 25 nm of origin");
            assert!((r - 98.08e-6).abs() < 25e-9, "fitted radius {r:e} should match 98.08 um within 25 nm");
            assert!(sweep > 0.0, "CCW hole boundary arcs are convex: sweep={sweep}");
            let (p_start, p_end) = arc_endpoints(c, r, a0, sweep);
            assert!((dist2(p_start, c) - r).abs() < 1e-19);
            assert!((dist2(p_end, c) - r).abs() < 1e-19);
        }
    }

    // Verify exact endpoint coincidence around the closed contour loop (||end_i - start_{i+1}|| == 0.0)
    let m = segs.len();
    for i in 0..m {
        let end_i = match segs[i].geom {
            DGeom::Line { p1, .. } => p1,
            DGeom::Arc { c, r, a0, sweep } => arc_endpoints(c, r, a0, sweep).1,
            _ => unreachable!(),
        };
        let start_next = match segs[(i + 1) % m].geom {
            DGeom::Line { p0, .. } => p0,
            DGeom::Arc { c, r, a0, sweep } => arc_endpoints(c, r, a0, sweep).0,
            _ => unreachable!(),
        };
        assert_eq!(
            dist2(end_i, start_next),
            0.0,
            "segment {i} end {end_i:?} must coincide bit-identically with segment {} start {start_next:?}",
            (i + 1) % m
        );
    }

    // Wrap-around invariance: rotate the 186-vertex ring so index 0 sits in the middle of the right arc
    let mut rotated = hole.clone();
    rotated.rotate_left(45);
    let rot_segs = fit_contour_arcs(&rotated, &vec![false; rotated.len()], 200e-9);
    let rot_arcs = rot_segs.iter().filter(|s| matches!(s.geom, DGeom::Arc { .. })).count();
    let rot_lines = rot_segs.iter().filter(|s| matches!(s.geom, DGeom::Line { .. })).count();
    assert_eq!(rot_segs.len(), 8);
    assert_eq!(rot_arcs, 2, "arc straddling index 0 must be fitted as a single continuous arc");
    assert_eq!(rot_lines, 6);
}

#[test]
fn pinned_vertices_act_as_mandatory_chain_delimiters_with_exact_endpoint_anchoring() {
    let hole = concentric_c0_hole();
    let mut pinned = vec![false; hole.len()];
    // Pin index 47 ([9.808e-5, 0.0]) in the middle of the right arc
    pinned[47] = true;
    let p_pin = hole[47];

    let segs = fit_contour_arcs(&hole, &pinned, 200e-9);
    let n_arcs = segs.iter().filter(|s| matches!(s.geom, DGeom::Arc { .. })).count();
    let n_lines = segs.iter().filter(|s| matches!(s.geom, DGeom::Line { .. })).count();
    assert_eq!(n_arcs, 3, "pinning 1 midpoint on the right arc must split it into 2 arcs (total 3 arcs)");
    assert_eq!(n_lines, 6);

    // One arc must end at p_pin and the next arc must start at p_pin within machine precision (< 1e-18 m)
    let mut saw_pin = false;
    for w in segs.windows(2) {
        if let (DGeom::Arc { c: c0, r: r0, a0: a00, sweep: sw0 }, DGeom::Arc { c: c1, r: r1, a0: a01, sweep: sw1 }) =
            (&w[0].geom, &w[1].geom)
        {
            let (_, end0) = arc_endpoints(*c0, *r0, *a00, *sw0);
            let (start1, _) = arc_endpoints(*c1, *r1, *a01, *sw1);
            assert!(dist2(end0, p_pin) < 1e-18, "arc0 end {end0:?} vs pin {p_pin:?}: {:e}", dist2(end0, p_pin));
            assert!(dist2(start1, p_pin) < 1e-18, "arc1 start {start1:?} vs pin {p_pin:?}: {:e}", dist2(start1, p_pin));
            saw_pin = true;
        }
    }
    assert!(saw_pin, "must find two consecutive arcs meeting at the pinned vertex");
}

#[test]
fn concave_arc_in_c1_and_concentric_stack_arrange_cleanly_with_exact_circle_areas() {
    let c1 = concentric_c1_outer();
    let segs_c1 = fit_contour_arcs(&c1, &vec![false; c1.len()], 200e-9);
    let arcs_c1: Vec<_> = segs_c1
        .iter()
        .filter_map(|s| match s.geom {
            DGeom::Arc { c, r, a0, sweep } => Some((c, r, a0, sweep)),
            _ => None,
        })
        .collect();
    let lines_c1 = segs_c1.iter().filter(|s| matches!(s.geom, DGeom::Line { .. })).count();
    assert_eq!(arcs_c1.len(), 3, "c1 must have 2 outer convex arcs and 1 inner concave arc");
    assert_eq!(lines_c1, 5, "c1 must have 5 straight tab/gap lines");
    assert!(
        arcs_c1.iter().any(|&(_, r, _, sweep)| sweep < -5.5 && (r - 75.55e-6).abs() < 10e-9),
        "c1 inner arc must be concave (sweep < 0, r ~= 75.55 um): {arcs_c1:?}"
    );

    // Build full 3D layer stack with c0 (outer rect minus 186-vertex hole) and c1 (186-vertex C-ring with concave inner arc)
    let mut m = Model::new_3d();
    let vac_top = m.box_("vac_top", (-0.00016208, -0.00018958, 0.0), (0.00016208, 0.00018958, 0.001));
    let vac_bot = m.box_("vac_bot", (-0.00016208, -0.00018958, -0.00135), (0.00016208, 0.00018958, -0.00035));
    let si_sub = m.box_("si_sub", (-0.00016208, -0.00018958, -0.00035), (0.00016208, 0.00018958, 0.0));

    let c0_outer = vec![
        [-0.00016208, -0.00018958],
        [0.00016208, -0.00018958],
        [0.00016208, 0.00018958],
        [-0.00016208, 0.00018958],
    ];
    let poly_c0 = m.polygons_with_arcs(
        "poly_c0",
        vec![to_expr_ring(&c0_outer)],
        vec![to_expr_ring(&concentric_c0_hole())],
        7.790615287643187e-07,
        0.0,
        200e-9,
    );
    let _c0 = m.sheet("c0", poly_c0, 0.0);

    let poly_c1 = m.polygons_with_arcs("poly_c1", vec![to_expr_ring(&c1)], vec![], 7.790615287643187e-07, 0.0, 200e-9);
    let _c1 = m.sheet("c1", poly_c1, 0.0);
    m.overlay(&[("VacTop", vac_top), ("VacBot", vac_bot), ("Si", si_sub)]);

    let ev = Evaluator::new().eval(&m.list, Tier::Complex).expect("concentric stack with concave arc must arrange");
    let st = ev.complex().stack.as_ref().expect("3D sheet stack");
    let n_circles = st.overlay.curves.iter().filter(|c| matches!(c, Curve::Circle { .. })).count();
    assert!(n_circles >= 3, "overlay must intern exact Curve::Circle curves, found {n_circles}");
}

#[test]
fn full_circle_area_and_arc_tol_zero_bit_identity() {
    let r_true = 50.0e-6;
    let n_pts = 96usize;
    let ring: Vec<V2> = (0..n_pts)
        .map(|i| {
            let a = TAU * (i as f64 / n_pts as f64);
            [r_true * a.cos(), r_true * a.sin()]
        })
        .collect();

    // 1. With arc_tol = 50e-9, 96-gon circle compresses to exact Circle with area within < 1e-6 of pi * R^2
    let mut m_arc = Model::new_2d();
    let f_arc = m_arc.polygons_with_arcs("disk", vec![to_expr_ring(&ring)], vec![], 500e-9, 0.0, 50e-9);
    m_arc.overlay(&[("Disk", f_arc)]);
    let ev_arc = Evaluator::new().eval(&m_arc.list, Tier::Complex).unwrap();
    let exact_area = std::f64::consts::PI * r_true * r_true;
    let got_area = ev_arc.complex().regions[0].measure;
    let rel_err = (got_area - exact_area).abs() / exact_area;
    assert!(rel_err < 1e-6, "fitted circle area relative error {rel_err:e} must be < 1e-6");

    // 2. When arc_tol == 0.0, Op::Polygons keeps LShape::Poly bit-identically
    let mut m_poly = Model::new_2d();
    let f_poly = m_poly.polygons_with_arcs("disk", vec![to_expr_ring(&ring)], vec![], 50e-9, 0.0, 0.0);
    m_poly.overlay(&[("Disk", f_poly)]);
    let ev_poly = Evaluator::new().eval(&m_poly.list, Tier::Complex).unwrap();
    assert!(matches!(ev_poly.scene.as_ref().unwrap().prims[0].shape, LShape::Poly { .. }));
}
