//! Interface contracts of nyx-connect (ADR 19 and ADR 28): what other programs depend on.
//!
//! * `connect_hosts` (v1): the table of hosts: id, name, config file (relative to the home folder) per operating system, the key that holds the
//!   servers and the entry written for a server. AI hosts that registered nyx weeks ago read these entries; a change here is a change of
//!   what a user's config file contains (`docs/architecture/contracts/connect_hosts.v1.json`).
//! * `connect_report` (v1): the JSON that `nyx-connect --json` prints, as examples (`connect_report.v1.json`) and as a JSON Schema generated by
//!   the code (`connect_report.v1.schema.json`). The examples and the live output of the program are validated against the schema.
//!
//! `NYX_WRITE_CONTRACT=1 cargo test --release -p nyx-connect --test contracts` rewrites the files (only with a `VERSIONS.md` line, ADR 19).
//! Files are compared as values, never as text (ADR 26).
mod common;
use common::*;
use nyx_connect::report::{change_report, change_row, list_report, schema, test_report};
use nyx_connect::*;
use serde_json::{json, Value};
use std::path::{Path, PathBuf};
use std::process::Command;

fn contract_file(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/architecture/contracts").join(name)
}

/// Compares `got` with the checked-in file as values; with `NYX_WRITE_CONTRACT` set, writes it instead.
fn check_exemplar(name: &str, got: &Value) {
    let path = contract_file(name);
    if std::env::var_os("NYX_WRITE_CONTRACT").is_some() {
        std::fs::write(&path, serde_json::to_string_pretty(got).unwrap() + "\n").unwrap();
        return;
    }
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let want: Value = serde_json::from_str(&text).unwrap();
    assert_eq!(&want, got, "{name} no longer matches the contract exemplar; this is a change of an interface (ADR 19, ADR 28): bump VERSIONS.md and rewrite it on purpose");
}

fn slash(p: &Path) -> String {
    p.to_string_lossy().replace('\\', "/")
}

