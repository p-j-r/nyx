fn hosts_table() -> Value {
    let exe = Path::new("/x/nyx-mcp");
    let mut by_os = serde_json::Map::new();
    for os in [Os::Windows, Os::Mac, Os::Linux] {
        let env = Env { home: PathBuf::from("/h"), appdata: Some(PathBuf::from("/h/AppData/Roaming")), local_appdata: Some(PathBuf::from("/nonexistent/Local")), os };
        let rows: Vec<Value> = hosts(&env)
            .iter()
            .map(|h| {
                json!({
                    "id": h.id,
                    "name": h.name,
                    "config": slash(h.config.strip_prefix("/h").unwrap_or(&h.config)),
                    "servers_key": h.servers_key(),
                    "after_connect": h.after_connect,
                    "entry": h.entry(exe),
                })
            })
            .collect();
        by_os.insert(os.name().into(), Value::Array(rows));
    }
    json!({ "entry_name": ENTRY, "server": "/x/nyx-mcp", "config_relative_to": "home", "hosts": by_os })
}

#[test]
fn connect_hosts_v1_exemplar_is_stable() {
    check_exemplar("connect_hosts.v1.json", &hosts_table());
}

#[test]
fn connect_hosts_v1_what_a_host_reads_back_is_the_entry_of_the_table() {
    // the entry the table promises is exactly what connect() puts in an empty config, for every host
    let sb = Sandbox::new("hosts_contract");
    let env = sb.env(Os::Linux);
    let exe = sb.exe();
    for h in hosts(&env) {
        connect(&env, h.id, &exe).unwrap();
        let v: Value = serde_json::from_str(&std::fs::read_to_string(&h.config).unwrap()).unwrap();
        assert_eq!(v[h.servers_key()][ENTRY], h.entry(&exe), "{}", h.id);
        assert_eq!(v.as_object().unwrap().len(), 1, "{}: nothing but the servers object is written into an empty file", h.id);
    }
}

