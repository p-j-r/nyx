/// A small JSON Schema validator for the keywords `report::schema` uses (`$ref`, `oneOf`, `const`, `enum`, `type`, `required`, `properties`,
/// `additionalProperties: false`, `items`). Unknown keywords make the test fail, so the schema cannot grow past the validator unnoticed.
fn validate(root: &Value, schema: &Value, inst: &Value, at: &str, errs: &mut Vec<String>) {
    const KNOWN: [&str; 14] = ["$schema", "$id", "title", "$defs", "$ref", "oneOf", "const", "enum", "type", "required", "properties", "additionalProperties", "items", "description"];
    let obj = schema.as_object().expect("a schema is an object");
    for k in obj.keys() {
        assert!(KNOWN.contains(&k.as_str()), "the test validator does not know the schema keyword {k}");
    }
    if let Some(r) = obj.get("$ref") {
        let name = r.as_str().unwrap().strip_prefix("#/$defs/").expect("only #/$defs refs");
        return validate(root, &root["$defs"][name], inst, at, errs);
    }
    if let Some(alts) = obj.get("oneOf") {
        let matching = alts.as_array().unwrap().iter().filter(|a| {
            let mut e = vec![];
            validate(root, a, inst, at, &mut e);
            e.is_empty()
        });
        let n = matching.count();
        if n != 1 {
            errs.push(format!("{at}: matches {n} of the oneOf alternatives, expected exactly 1"));
        }
    }
    if let Some(c) = obj.get("const") {
        if c != inst {
            errs.push(format!("{at}: expected {c}, found {inst}"));
        }
    }
    if let Some(e) = obj.get("enum") {
        if !e.as_array().unwrap().contains(inst) {
            errs.push(format!("{at}: {inst} is not one of {e}"));
        }
    }
    if let Some(t) = obj.get("type") {
        let types: Vec<&str> = match t {
            Value::String(s) => vec![s.as_str()],
            Value::Array(a) => a.iter().map(|x| x.as_str().unwrap()).collect(),
            _ => panic!("bad type keyword"),
        };
        let ok = types.iter().any(|t| match *t {
            "object" => inst.is_object(),
            "array" => inst.is_array(),
            "string" => inst.is_string(),
            "boolean" => inst.is_boolean(),
            "null" => inst.is_null(),
            "integer" => inst.is_i64() || inst.is_u64(),
            "number" => inst.is_number(),
            other => panic!("unknown type {other}"),
        });
        if !ok {
            errs.push(format!("{at}: expected type {types:?}, found {inst}"));
        }
    }
    if let Some(m) = inst.as_object() {
        for k in obj.get("required").and_then(Value::as_array).into_iter().flatten() {
            if !m.contains_key(k.as_str().unwrap()) {
                errs.push(format!("{at}: missing key {k}"));
            }
        }
        let props = obj.get("properties").and_then(Value::as_object);
        for (k, v) in m {
            match props.and_then(|p| p.get(k)) {
                Some(s) => validate(root, s, v, &format!("{at}/{k}"), errs),
                None if obj.get("additionalProperties") == Some(&json!(false)) => errs.push(format!("{at}: unexpected key {k}")),
                None => {}
            }
        }
    }
    if let (Some(items), Some(a)) = (obj.get("items"), inst.as_array()) {
        for (i, v) in a.iter().enumerate() {
            validate(root, items, v, &format!("{at}/{i}"), errs);
        }
    }
}

fn errors(inst: &Value) -> Vec<String> {
    let s = schema();
    let mut e = vec![];
    validate(&s, &s, inst, "", &mut e);
    e
}

fn assert_valid(inst: &Value) {
    let e = errors(inst);
    assert!(e.is_empty(), "{}\nis not a valid report:\n{}", serde_json::to_string_pretty(inst).unwrap(), e.join("\n"));
}

fn host_info(id: &'static str, name: &'static str, status: Status) -> HostInfo {
    HostInfo { id, name, config: PathBuf::from(format!("/h/{id}.json")), after_connect: "Restart it to use it.", status }
}

fn report_examples() -> Vec<(&'static str, Value)> {
    let exe = Path::new("/x/nyx-mcp");
    let list = list_report(
        exe,
        &[
            host_info("claude-code", "Claude Code", Status::Connected),
            host_info("claude-desktop", "Claude Desktop", Status::Stale { found: "/old/nyx-mcp".into() }),
            host_info("cursor", "Cursor", Status::NotConnected),
            host_info("vscode", "VS Code", Status::Unreadable { why: "/h/mcp.json is not plain JSON (expected value at line 2); it may contain comments. Not changed: add the entry by hand (see the snippet)".into() }),
            host_info("windsurf", "Windsurf", Status::NotInstalled),
            host_info("antigravity", "Antigravity", Status::Connected),
        ],
    );
    let done = |changed, backup: Option<&str>| Done { host: "cursor", config: PathBuf::from("/h/.cursor/mcp.json"), backup: backup.map(PathBuf::from), changed };
    let change = change_report(
        "connect",
        vec![
            change_row("cursor", &Ok(done(true, Some("/h/.cursor/mcp.json.nyx-backup")))),
            change_row("claude-code", &Ok(done(false, None))),
            change_row("vscode", &Err("no host 'vscode2'; valid: claude-code, claude-desktop, cursor, vscode, windsurf, antigravity".into())),
        ],
    );
    let ok = test_report(&Ok(ServerInfo { name: "nyx-mcp".into(), version: "0.1.0".into(), protocol: "2025-06-18".into(), tools: vec!["geometry_build".into(), "solve".into()] }));
    let bad = test_report(&Err("no answer to initialize within 10 s".into()));
    // the file's own list report is only valid with `server_found` computed from disk; the example is built with a path that does not exist
    vec![("list", list), ("change", change), ("test_ok", ok), ("test_failed", bad)]
}

#[test]
fn connect_report_v1_schema_is_the_one_in_the_contract() {
    check_exemplar("connect_report.v1.schema.json", &schema());
}

#[test]
fn connect_report_v1_exemplar_is_stable_and_valid_against_the_schema() {
    let examples = report_examples();
    let doc: serde_json::Map<String, Value> = examples.iter().map(|(k, v)| (k.to_string(), v.clone())).collect();
    check_exemplar("connect_report.v1.json", &Value::Object(doc));
    for (name, v) in &examples {
        assert_valid(v);
        assert_eq!(v["version"], 1, "{name}");
    }
}

#[test]
fn connect_report_v1_the_validator_is_not_vacuous() {
    let list = &report_examples()[0].1;
    let mut cases: Vec<(&str, Value)> = vec![];
    let mut v = list.clone();
    v["version"] = json!(2);
    cases.push(("another version", v));
    let mut v = list.clone();
    v["hosts"][0]["status"]["state"] = json!("fine");
    cases.push(("unknown state", v));
    let mut v = list.clone();
    v["hosts"][1]["status"] = json!({ "state": "stale" });
    cases.push(("stale without found", v));
    let mut v = list.clone();
    v["hosts"][0]["extra"] = json!(1);
    cases.push(("unexpected key", v));
    let mut v = list.clone();
    v["hosts"][0]["id"] = json!("emacs");
    cases.push(("unknown host id", v));
    let mut v = list.clone();
    v.as_object_mut().unwrap().remove("server");
    cases.push(("missing server", v));
    let mut v = report_examples()[1].1.clone();
    v["results"][0]["backup"] = json!(5);
    cases.push(("backup of the wrong type", v));
    let mut v = report_examples()[1].1.clone();
    v["results"][2] = json!({ "host": "vscode", "ok": false });
    cases.push(("failed row without error", v));
    let mut v = report_examples()[2].1.clone();
    v["server"]["tools"] = json!("solve");
    cases.push(("tools not an array", v));
    for (what, inst) in cases {
        assert!(!errors(&inst).is_empty(), "the validator accepted a report with {what}");
    }
}

/// Runs the built `nyx-connect` program on a sandbox machine and returns (exit code, stdout).
fn run(sb: &Sandbox, server: &Path, args: &[&str]) -> (i32, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nyx-connect"))
        .args(args)
        .env("USERPROFILE", sb.0.join("home"))
        .env("HOME", sb.0.join("home"))
        .env("APPDATA", sb.0.join("home/AppData/Roaming"))
        .env("LOCALAPPDATA", sb.0.join("home/AppData/Local"))
        .env("NYX_MCP", server)
        .output()
        .expect("run nyx-connect");
    (out.status.code().unwrap_or(-1), String::from_utf8_lossy(&out.stdout).into_owned())
}

#[test]
fn connect_report_v1_the_program_prints_valid_reports() {
    let sb = Sandbox::new("cli");
    let fake = fake_mcp();
    std::fs::create_dir_all(sb.0.join("home/.cursor")).unwrap();
    std::fs::create_dir_all(sb.0.join("home/.claude")).unwrap();

    let (code, out) = run(&sb, &fake, &["list", "--json"]);
    assert_eq!(code, 0);
    let list: Value = serde_json::from_str(&out).unwrap();
    assert_valid(&list);
    assert_eq!(list["server_found"], true);
    let states: Vec<(&str, &str)> = list["hosts"].as_array().unwrap().iter().map(|h| (h["id"].as_str().unwrap(), h["status"]["state"].as_str().unwrap())).collect();
    assert_eq!(states, [("claude-code", "not_connected"), ("claude-desktop", "not_installed"), ("cursor", "not_connected"), ("vscode", "not_installed"), ("windsurf", "not_installed"), ("antigravity", "not_installed")]);

    let (code, out) = run(&sb, &fake, &["connect", "all", "--json"]);
    assert_eq!(code, 0);
    let change: Value = serde_json::from_str(&out).unwrap();
    assert_valid(&change);
    let hosts_done: Vec<&str> = change["results"].as_array().unwrap().iter().map(|r| r["host"].as_str().unwrap()).collect();
    assert_eq!(hosts_done, ["claude-code", "cursor"], "'all' means every installed host");
    assert!(change["results"].as_array().unwrap().iter().all(|r| r["ok"] == true && r["changed"] == true));

    let (_, out) = run(&sb, &fake, &["list", "--json"]);
    let list: Value = serde_json::from_str(&out).unwrap();
    assert_valid(&list);
    assert_eq!(list["hosts"][0]["status"]["state"], "connected");

    let (code, out) = run(&sb, &fake, &["disconnect", "cursor", "--json"]);
    assert_eq!(code, 0);
    let gone: Value = serde_json::from_str(&out).unwrap();
    assert_valid(&gone);
    assert_eq!(gone["action"], "disconnect");

    // a refused connect is a failed row and exit code 1, still a valid report
    let (code, out) = run(&sb, &fake, &["connect", "emacs", "--json"]);
    assert_eq!(code, 1);
    let refused: Value = serde_json::from_str(&out).unwrap();
    assert_valid(&refused);
    assert_eq!(refused["results"][0]["ok"], false);

    let (code, out) = run(&sb, &fake, &["test", "--json"]);
    assert_eq!(code, 0);
    let t: Value = serde_json::from_str(&out).unwrap();
    assert_valid(&t);
    assert_eq!(t["server"]["name"], "fake-nyx");

    let (code, out) = run(&sb, &sb.0.join("missing-server"), &["test", "--json"]);
    assert_eq!(code, 1);
    let t: Value = serde_json::from_str(&out).unwrap();
    assert_valid(&t);
    assert_eq!(t["ok"], false);

    // the plain-text form keeps working and says the same
    let (code, out) = run(&sb, &fake, &["list"]);
    assert_eq!(code, 0);
    assert!(out.contains("claude-code") && out.contains("connected"), "{out}");
}
